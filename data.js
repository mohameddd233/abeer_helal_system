function installBuiltinLessons() {
    if (localStorage.getItem(BUILTIN_INSTALLED) === 'true') return;
    let lessons = getLessons();
    BUILTIN_LESSONS.forEach(bl => { if (!lessons.find(l => l.id === bl.id)) lessons.push({ ...bl }); });
    setLessons(lessons);
    localStorage.setItem(BUILTIN_INSTALLED, 'true');
}
function getMissingBuiltinCount() {
    const lessons = getLessons();
    return BUILTIN_LESSONS.filter(bl => !lessons.find(l => l.id === bl.id)).length;
}
function restoreBuiltinLessons() {
    const missing = getMissingBuiltinCount();
    if (missing === 0) { showToast('كل الدروس الأساسية موجودة بالفعل', 'success'); return; }
    let lessons = getLessons();
    let restored = 0;
    BUILTIN_LESSONS.forEach(bl => {
        if (!lessons.find(l => l.id === bl.id)) { lessons.push({ ...bl, restoredAt: new Date().toISOString() }); restored++; }
    });
    setLessons(lessons);
    showToast(`تم استرجاع ${restored} درس أساسي`, 'success');
    renderLessons();
    renderDashboard();
}

